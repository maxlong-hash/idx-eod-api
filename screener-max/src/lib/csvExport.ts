export function serializeMaxScreenerCsvRows(rows: readonly (readonly unknown[])[]) {
  return rows.map((row) => row.map((cell) => `"${String(cell).replaceAll('"', '""')}"`).join(',')).join('\n');
}

export function buildMaxScreenerCsv(results: ScanResult[]) {
  return serializeMaxScreenerCsvRows(buildMaxScreenerRows(results));
}
