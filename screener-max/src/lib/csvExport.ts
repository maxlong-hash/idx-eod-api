export function formatSignalList(signals: SignalName[]) {
  return signals.length ? signals.join(' + ') : '-';
}

export function formatSignalAge(result: ScanResult) {
  if (result.ageDays >= 999) return '-';
  return result.ageDays <= 1 ? 'NEW' : `${result.ageDays}d`;
}

export function getMaxScreenerExportDate(results: ScanResult[]) {
  return results.reduce(
    (current, item) => (item.latestDate > current ? item.latestDate : current),
    results[0]?.latestDate ?? new Date().toISOString().slice(0, 10),
  );
}

